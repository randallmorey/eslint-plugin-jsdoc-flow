// Generates `lib/index.d.ts` from the plugin itself:  its rules, its configs,
// the settings' schema and each rule's options schema, so the types can't
// drift from what runs.  Run it with `npm run types`;  a test fails when
// the file is stale.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

import plugin from '../lib/index.js';
import { SETTINGS_SCHEMA } from '../lib/settings.js';

export const DTS = fileURLToPath(new URL('../lib/index.d.ts', import.meta.url));

// The keywords a schema here may use.  The rest can't be typed as they are,
// so one of them is an error rather than a type that's quietly too loose.
const KEYWORDS = new Set([
  'description',
  'type',
  'enum',
  'items',
  'properties',
  'additionalProperties',
  'uniqueItems',
  'minimum',
  'maximum',
  'pattern',
]);

// A JSDoc comment of a description, wrapped to fit beside its indent.
function docOf(description) {
  if (!description) return '';
  const lines = [''];
  for (const word of description.split(' ')) {
    const line = lines.at(-1);
    if (line && `${line} ${word}`.length > 72) lines.push(word);
    else lines[lines.length - 1] = line ? `${line} ${word}` : word;
  }
  return `/**\n${lines.map((l) => ` * ${l}`.trimEnd()).join('\n')}\n */\n`;
}

// The TypeScript type of the values a JSON schema accepts.
export function typeOf(schema) {
  const unknown = Object.keys(schema).find((key) => !KEYWORDS.has(key));
  if (unknown) throw new Error(`The schema keyword ${unknown} isn't typed.`);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  switch (schema.type) {
    case 'boolean':
    case 'string':
      return schema.type;
    case 'number':
    case 'integer':
      return 'number';
    case 'array':
      return `${typeOf(schema.items)}[]`;
    case 'object': {
      if (schema.additionalProperties !== false) {
        throw new Error('An object schema must set additionalProperties.');
      }
      const members = Object.entries(schema.properties ?? {}).map(
        ([key, value]) =>
          `${docOf(value.description)}${JSON.stringify(key)}?: ${typeOf(value)};`,
      );
      return `{\n${members.join('\n')}\n}`;
    }
  }
  throw new Error(`The schema type ${schema.type} isn't typed.`);
}

const pascal = (name) =>
  name.replace(/(?:^|-)(\w)/g, (_, letter) => letter.toUpperCase());

// The text of `lib/index.d.ts`.
export async function generate() {
  const interfaces = [
    docOf(
      "The settings that all the rules share, from `settings['jsdoc-flow']`.",
    ) + `export interface Settings ${typeOf(SETTINGS_SCHEMA)}`,
  ];
  const options = Object.entries(plugin.rules).map(([name, rule]) => {
    const { schema = [] } = rule.meta;
    if (!Array.isArray(schema))
      throw new Error(`${name}'s schema isn't a list.`);
    const types = schema.map((item, k) => {
      const type = `${pascal(name)}Options${k ? k + 1 : ''}`;
      interfaces.push(
        docOf(`The options of \`jsdoc-flow/${name}\`.`) +
          `export interface ${type} ${typeOf(item)}`,
      );
      return `${type}?`;
    });
    return `${JSON.stringify(name)}: [${types.join(', ')}];`;
  });
  const configs = Object.keys(plugin.configs).map(
    (name) => `${JSON.stringify(name)}: Linter.Config;`,
  );
  const text = `// Generated by \`npm run types\` from the plugin's rules, configs and
// schemas.  Don't edit it by hand.
import type { Linter, Rule } from 'eslint';

${interfaces.join('\n\n')}

/**
 * Each rule's options, by its name in the plugin.
 */
export interface RuleOptions {
${options.join('\n')}
}

/**
 * The plugin's rules as a config's \`rules\` takes them, as in
 * \`rules: { ... } satisfies Rules\`.
 */
export type Rules = {
  [Name in keyof RuleOptions as \`jsdoc-flow/\${Name}\`]?: Linter.RuleEntry<
    RuleOptions[Name]
  >;
};

/**
 * The plugin, which is an \`ESLint.Plugin\`.
 */
declare const plugin: {
  meta: { name: string; version: string };
  rules: { [Name in keyof RuleOptions]: Rule.RuleModule };
  configs: {
${configs.join('\n')}
  };
};

export default plugin;
`;
  const config = await prettier.resolveConfig(DTS);
  return prettier.format(text, { ...config, filepath: DTS });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(DTS, await generate());
}
